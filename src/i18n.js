export const LANGUAGES = ['zh', 'en'];

const messages = { zh, en };

export function detectLanguage() {
  try {
    const saved = window.localStorage.getItem('bearTogether.lang');
    if (saved && LANGUAGES.includes(saved)) return saved;
  } catch {
    // Storage may be unavailable; fall back to the browser language.
  }
  try {
    const browser = (navigator.languages?.[0] || navigator.language || '').toLowerCase();
    return browser.startsWith('zh') ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export function translate(language, key, params = null) {
  const table = messages[language] || messages.en;
  const template = table[key] ?? messages.zh[key] ?? key;
  if (!params) return template;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => {
    if (params[name] === undefined || params[name] === null) return match;
    return String(params[name]);
  });
}
